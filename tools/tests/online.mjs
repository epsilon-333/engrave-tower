// 온라인 중계 서버: 두 사람이 접속해 서로 보이고, 채팅하고, 결투를 시작 · 주고받고 · 끝내는지
import { spawn } from 'node:child_process';
const PORT = 5199, root = new URL('../../', import.meta.url);
const srv = spawn(process.execPath, ['server.js'], { cwd: root, env: { ...process.env, PORT: String(PORT) }, stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 600));
const open = (name) => new Promise((res) => {
  const ws = new WebSocket(`ws://localhost:${PORT}/ws`), inbox = [];
  ws.onmessage = (e) => inbox.push(JSON.parse(e.data));
  ws.onopen = () => { ws.send(JSON.stringify({ t: 'hello', name, race: 'knight', cls: 'greatsword', weapon: 'steelGreatsword', lv: 7 })); res({ ws, inbox, send: (o) => ws.send(JSON.stringify(o)) }); };
});
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const has = (c, t) => c.inbox.find((m) => m.t === t);
const ok = (cond, text) => { console.log(cond ? 'OK ' : 'FAIL', text); if (!cond) process.exitCode = 1; };
const a = await open('가람'), b = await open('나래');
await wait(150);
const ida = has(a, 'welcome').id, idb = has(b, 'welcome').id;
a.send({ t: 'map', map: 'world', x: 10, y: 10 }); await wait(80); b.send({ t: 'map', map: 'world', x: 50, y: 10 }); await wait(150);
ok(has(a, 'join')?.p.name === '나래', '같은 지도에 들어오면 서로 보인다');
ok(has(b, 'players')?.list.some((p) => p.name === '가람'), '들어온 사람은 먼저 있던 사람 목록을 받는다');
b.send({ t: 'pos', x: 60, y: 12, dir: -1, mo: 'run' }); await wait(100);
ok(a.inbox.some((m) => m.t === 'pos' && m.id === idb && m.x === 60), '움직임이 전해진다');
a.send({ t: 'chat', text: '안녕 <b>하세요</b>' }); await wait(100);
ok(has(b, 'chat')?.text === '안녕 b하세요/b', '채팅이 전해지고 태그 글자는 지워진다');
a.send({ t: 'duelInvite', to: idb }); await wait(100);
ok(has(b, 'duelInvite')?.from === ida, '결투 신청이 상대에게 간다');
b.send({ t: 'duelAnswer', to: ida, ok: true, maxHp: 180 }); await wait(120);
ok(has(a, 'duelStart')?.opp.name === '나래' && has(b, 'duelStart')?.side === 1, '수락하면 둘 다 결투를 시작한다');
a.send({ t: 'dhit', dmg: 42, type: 'phys' }); await wait(100);
ok(b.inbox.some((m) => m.t === 'dhit' && m.dmg === 42 && m.from === ida), '결투 중 공격이 상대에게 간다');
b.send({ t: 'dend', reason: 'down' }); await wait(100);
ok(a.inbox.some((m) => m.t === 'dend' && m.loser === idb), '쓰러지면 상대에게 승리가 알려진다');
a.send({ t: 'duelInvite', to: idb }); await wait(80); b.send({ t: 'duelAnswer', to: ida, ok: true, maxHp: 180 }); await wait(120);
a.send({ t: 'dend', reason: 'time', win: true }); await wait(100);
ok(b.inbox.some((m) => m.t === 'dend' && m.reason === 'time' && m.loser === idb), '시간이 다 돼 이긴 쪽이 알리면 상대가 진 것으로 간다');
a.send({ t: 'duelInvite', to: idb }); await wait(100);
ok(b.inbox.filter((m) => m.t === 'duelInvite').length === 3, '결투가 끝나면 다시 신청할 수 있다');
b.ws.close(); await wait(150);
ok(a.inbox.some((m) => m.t === 'leave' && m.id === idb), '나가면 지도에서 사라진다');
a.ws.close(); srv.kill();
